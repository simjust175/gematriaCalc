BEGIN;

CREATE TABLE tefillot_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_work TEXT NOT NULL,
  source_version TEXT NOT NULL,
  version_source TEXT NOT NULL,
  license TEXT NOT NULL CHECK (license IN ('Public Domain', 'CC-BY', 'CC0')),
  source_url TEXT NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (source_work, source_version, source_url)
);

CREATE TABLE tefillot_units (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id BIGINT NOT NULL REFERENCES tefillot_sources(id) ON DELETE RESTRICT,
  nusach TEXT NOT NULL CHECK (nusach = 'sefard'),
  occasion_slug TEXT NOT NULL,
  occasion_label TEXT NOT NULL,
  occasion_order INTEGER NOT NULL CHECK (occasion_order > 0),
  service_slug TEXT NOT NULL,
  service_label TEXT NOT NULL,
  service_order INTEGER NOT NULL CHECK (service_order > 0),
  section_key TEXT NOT NULL,
  section_label TEXT NOT NULL,
  section_order INTEGER NOT NULL CHECK (section_order > 0),
  subsection TEXT,
  sequence INTEGER NOT NULL CHECK (sequence > 0),
  hebrew_text TEXT NOT NULL CHECK (length(btrim(hebrew_text)) > 0),
  normalized_hebrew_text TEXT NOT NULL CHECK (length(btrim(normalized_hebrew_text)) > 0),
  source_reference TEXT NOT NULL,
  source_work TEXT NOT NULL,
  source_version TEXT NOT NULL,
  license TEXT NOT NULL CHECK (license IN ('Public Domain', 'CC-BY', 'CC0')),
  UNIQUE (source_id, nusach, occasion_slug, service_slug, section_key, sequence)
);

CREATE INDEX idx_tefillot_units_section
  ON tefillot_units (occasion_slug, service_slug, section_key, section_order, sequence);

COMMIT;